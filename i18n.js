  function normalizeLanguage(language) {
    return language === 'pl' ? 'pl' : 'en';
  }

  function substitute(text, substitutions) {
    if (substitutions == null) return text;
    const values = Array.isArray(substitutions) ? substitutions : [substitutions];
    return String(text).replace(/\$(\d+)/g, (_, n) => values[Number(n) - 1] ?? '');
  }

  function getMessage(key, language, substitutions) {
    const lang = normalizeLanguage(language);
    const message = MESSAGES[lang]?.[key] ?? MESSAGES.en?.[key] ?? key;
    return substitute(message, substitutions);
  }

  function localizeDocument(language, root = document) {
    const lang = normalizeLanguage(language);
    if (root.documentElement) root.documentElement.lang = lang;
    root.querySelectorAll?.('[data-i18n]').forEach(el => {
      const value = getMessage(el.dataset.i18n, lang);
      if (value) el.textContent = value;
    });
  }

  globalThis.LL_I18N = { MESSAGES, normalizeLanguage, getMessage, localizeDocument };
